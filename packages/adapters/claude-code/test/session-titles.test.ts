import assert from "node:assert/strict";
import { mkdir, writeFile } from "node:fs/promises";
import { mkdtemp } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { after, describe, it } from "node:test";
import { projectDirSlug } from "../src/project-slug.js";
import { resolveSessionTitle } from "../src/session-titles.js";

describe("resolveSessionTitle", () => {
  let configDir = "";
  const projectDir = "/workspace/demo";
  const sessionId = "11111111-2222-3333-4444-555555555555";

  after(async () => {
    if (configDir !== "") {
      const { rm } = await import("node:fs/promises");
      await rm(configDir, { recursive: true, force: true });
    }
  });

  it("prefers customTitle from sessions-index.json", async () => {
    configDir = await mkdtemp(path.join(tmpdir(), "claude-titles-"));
    const slugDir = path.join(
      configDir,
      "projects",
      projectDirSlug(projectDir),
    );
    await mkdir(slugDir, { recursive: true });
    await writeFile(
      path.join(slugDir, "sessions-index.json"),
      JSON.stringify({
        version: 1,
        entries: [
          {
            sessionId,
            customTitle: "payment refactor",
            firstPrompt: "fix the login bug",
          },
        ],
      }),
    );
    await writeFile(path.join(slugDir, `${sessionId}.jsonl`), "");

    assert.equal(
      await resolveSessionTitle(configDir, projectDir, sessionId),
      "payment refactor",
    );
  });

  it("falls back to the first user message in jsonl", async () => {
    configDir = await mkdtemp(path.join(tmpdir(), "claude-titles-"));
    const slugDir = path.join(
      configDir,
      "projects",
      projectDirSlug(projectDir),
    );
    await mkdir(slugDir, { recursive: true });
    const jsonl = JSON.stringify({
      type: "user",
      uuid: "u1",
      message: {
        role: "user",
        content: [{ type: "text", text: "what is in this repo?" }],
      },
    });
    await writeFile(path.join(slugDir, `${sessionId}.jsonl`), jsonl);

    assert.equal(
      await resolveSessionTitle(configDir, projectDir, sessionId),
      "what is in this repo?",
    );
  });

  it("skips the CLI's own records when the session opened with a slash command", async () => {
    // Verbatim record shapes from a session whose first act was `/model haiku`:
    // the CLI writes a meta caveat, the command echo and the command's stdout
    // as `type: "user"` before the operator's first real prompt. Taking the
    // first user record at face value titled the session
    // "<local-command-caveat>".
    configDir = await mkdtemp(path.join(tmpdir(), "claude-titles-"));
    const slugDir = path.join(
      configDir,
      "projects",
      projectDirSlug(projectDir),
    );
    await mkdir(slugDir, { recursive: true });
    const lines = [
      { type: "queue-operation" },
      {
        type: "user",
        uuid: "u0",
        isMeta: true,
        message: {
          role: "user",
          content:
            "<local-command-caveat>Caveat: The messages below were generated by the user while running local commands.</local-command-caveat>",
        },
      },
      {
        type: "user",
        uuid: "u1",
        message: {
          role: "user",
          content:
            "<command-name>/model</command-name>\n<command-message>model</command-message>\n<command-args>haiku</command-args>",
        },
      },
      {
        type: "user",
        uuid: "u2",
        message: {
          role: "user",
          content:
            "<local-command-stdout>Set model to haiku (claude-haiku-4-5-20251001)</local-command-stdout>",
        },
      },
      {
        type: "user",
        uuid: "u3",
        message: {
          role: "user",
          content: [
            { type: "text", text: "what feature is missing in this project?" },
          ],
        },
      },
    ];
    await writeFile(
      path.join(slugDir, `${sessionId}.jsonl`),
      lines.map((line) => JSON.stringify(line)).join("\n"),
    );

    assert.equal(
      await resolveSessionTitle(configDir, projectDir, sessionId),
      "what feature is missing in this pr…",
    );
  });

  it("uses summary when index has no customTitle and jsonl has no user turn", async () => {
    configDir = await mkdtemp(path.join(tmpdir(), "claude-titles-"));
    const slugDir = path.join(
      configDir,
      "projects",
      projectDirSlug(projectDir),
    );
    await mkdir(slugDir, { recursive: true });
    await writeFile(
      path.join(slugDir, "sessions-index.json"),
      JSON.stringify({
        version: 1,
        entries: [
          {
            sessionId,
            summary: "Explored auth flow and fixed redirect",
          },
        ],
      }),
    );
    await writeFile(path.join(slugDir, `${sessionId}.jsonl`), "");

    assert.equal(
      await resolveSessionTitle(configDir, projectDir, sessionId),
      "Explored auth flow and fixed redir…",
    );
  });

  it("truncates long titles to 35 characters", async () => {
    configDir = await mkdtemp(path.join(tmpdir(), "claude-titles-"));
    const slugDir = path.join(
      configDir,
      "projects",
      projectDirSlug(projectDir),
    );
    await mkdir(slugDir, { recursive: true });
    await writeFile(
      path.join(slugDir, "sessions-index.json"),
      JSON.stringify({
        version: 1,
        entries: [
          {
            sessionId,
            customTitle: "this is a very long session title indeed",
          },
        ],
      }),
    );
    await writeFile(path.join(slugDir, `${sessionId}.jsonl`), "");

    assert.equal(
      await resolveSessionTitle(configDir, projectDir, sessionId),
      "this is a very long session title …",
    );
  });
});
