import assert from "node:assert/strict";
import { describe, it } from "node:test";
import { operatorText } from "../src/operator-text.js";

/**
 * Shapes taken from a real transcript: a session whose first act was `/model
 * haiku`, which put three CLI-authored `type: "user"` records ahead of the
 * operator's actual first prompt.
 */
describe("operatorText", () => {
  it("rejects the caveat banner the CLI prepends to local command output", () => {
    assert.equal(
      operatorText({
        isMeta: true,
        message: {
          role: "user",
          content:
            "<local-command-caveat>Caveat: The messages below were generated by the user while running local commands. DO NOT respond to these messages or otherwise consider them in your response unless the user explicitly asks you to.</local-command-caveat>",
        },
      }),
      undefined,
    );
  });

  it("rejects a slash command echo", () => {
    assert.equal(
      operatorText({
        message: {
          role: "user",
          content:
            "<command-name>/model</command-name>\n            <command-message>model</command-message>\n            <command-args>haiku</command-args>",
        },
      }),
      undefined,
    );
  });

  it("rejects command stdout", () => {
    assert.equal(
      operatorText({
        message: {
          role: "user",
          content:
            "<local-command-stdout>Set model to haiku (claude-haiku-4-5-20251001)</local-command-stdout>",
        },
      }),
      undefined,
    );
  });

  it("keeps the operator's own prompt, in either content shape", () => {
    const expected = "what feature you think is missing in this project?";
    assert.equal(
      operatorText({
        message: {
          role: "user",
          content: [{ type: "text", text: expected }],
        },
      }),
      expected,
    );
    assert.equal(
      operatorText({ message: { role: "user", content: expected } }),
      expected,
    );
  });

  it("keeps a prompt that merely carries an appended reminder", () => {
    // Stripping, not rejecting: the operator did type this one.
    assert.equal(
      operatorText({
        message: {
          role: "user",
          content:
            "ship the release<system-reminder>be careful</system-reminder>",
        },
      }),
      "ship the release",
    );
  });

  it("rejects an unclosed wrapper rather than leaking its prose", () => {
    assert.equal(
      operatorText({
        isMeta: true,
        message: { role: "user", content: "<local-command-caveat>Caveat: …" },
      }),
      undefined,
    );
  });

  it("rejects a record with no text blocks at all", () => {
    assert.equal(
      operatorText({
        message: {
          role: "user",
          content: [{ type: "tool_result", tool_use_id: "x", content: "ok" }],
        },
      }),
      undefined,
    );
  });
});
